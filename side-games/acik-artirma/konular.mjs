const slug = (s) => s.toLocaleLowerCase('tr')
  .replace(/[çğıöşüâîûé]/g, (c) => ({ ç: 'c', ğ: 'g', ı: 'i', ö: 'o', ş: 's', ü: 'u', â: 'a', î: 'i', û: 'u', é: 'e' })[c])
  .normalize('NFD').replace(/[̀-ͯ]/g, '')
  .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

export const KONULAR = RAW.map((k) => ({
  ...k,
  maddeler: k.maddeler.map(([ad, kunye, kontrol]) => ({ id: `${k.id}/${slug(ad)}`, ad, kunye, kontrol: !!kontrol })),
}));

'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const image=fs.readFileSync(path.join(root,'assets/entry/first-login-v1.png'));
assert.equal(image.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Approved image must be a PNG');
assert.equal(image.readUInt32BE(16),941,'Approved artwork width changed');
assert.equal(image.readUInt32BE(20),1672,'Approved artwork height changed');
assert(image.length>200000,'Only the exact full-resolution artwork may be used');
const code=read('side-games/neon-entry-v1.js');
const css=read('side-games/neon-entry-v1.css');
const social=read('social/neon-social.js');
const index=read('index.html');
assert(code.includes("new URL('./assets/entry/first-login-v1.png',document.baseURI)"),'Image asset path missing');
assert(code.includes('viewBox="0 0 941 1672"'),'Image and SVG controls must share source coordinates');
for(const action of ['google','guest','help'])assert(code.includes('data-entry-action="'+action+'"'),'Missing image control '+action);
assert(css.includes('width:min(100vw,56.2799dvh)'),'Responsive image ratio changed');
assert(css.includes('#nxEntry[hidden]'),'Signed-in screen must be hidden');
assert(social.includes('window.NEON_XI_ENTRY?.resolveAuth?.(user)'),'Entry screen must reuse the primary Firebase auth observer');
assert(!index.includes('neon-entry-auth-v1.js'),'Do not load a second delayed Firebase auth observer');
const guestFlow=social.slice(social.indexOf('async function continueAsGuest()'),social.indexOf('async function signOutGoogle()'));
assert(guestFlow.indexOf('await signOut(auth)')<guestFlow.indexOf('await signInAnonymously(auth)'),'Every explicit guest login must replace the previous Firebase identity');
assert(code.includes("api[method]()"),'Buttons must delegate to existing social auth implementation');
assert(code.includes("window.NEON_XI_ENTRY={"),'Welcome controller bridge missing');
assert(code.includes("if(!wasGuest&&!social?.profile)"),'New Google accounts must see the username chooser; guests land on the home screen');
assert(code.includes("guide.hidden=false"),'Help button must open real guide');
for(const file of ['neon-entry-v1.css','neon-entry-v1.js'])assert(index.includes('./side-games/'+file+"?v='+VERSION"),'Root must load '+file);
assert(/const VERSION='20\d{6}-[a-z0-9-]+'/.test(index),'A dated and explicit cache token is required for injected assets');
new Function(code);
console.log('PASS: approved artwork resolution, pixel-aligned login controls, single auth restoration observer, fresh guest identity per login, persistent sessions and guidance.');
